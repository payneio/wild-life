#!/usr/bin/env node
/**
 * Regenerate the two committed artifacts the web app derives from the API:
 * `src/services/api/schema.gen.ts` (types) and `src/services/api/lifecycle.gen.ts`
 * (the canonical status → phase table).
 *
 * Deterministic throughout: re-export `api/openapi.json` and `api/lifecycle.json`
 * from Python, then compile each to TypeScript. All four artifacts are committed,
 * so `pnpm build` never needs Python — only `pnpm gen:api` does, and only when the
 * API contract changed.
 *
 * The lifecycle table is generated rather than mirrored for the same reason the
 * types are: it is *semantics* the backend owns (`api/src/wild_life/lifecycle.py`),
 * and the one hand-written copy that existed — `routers/tasks.py`'s
 * `_CLOSED_STATUSES` — had already drifted from it. Note that the repo's usual
 * `as const satisfies readonly XStatus[]` guard could not have protected a
 * hand-written version: that idiom catches renames and removals but *not*
 * additions, and a terminal-status list is by definition a subset. The generated
 * table is total, so `src/services/api/lifecycle.ts` can assert exhaustiveness
 * with `Record<XStatus, LifecyclePhase>` and fail the build on a new status.
 *
 * The `transform` hook maps OpenAPI `format` onto the branded scalars in
 * `@/lib/date`, so a CalendarDay stays distinguishable from an Instant in the
 * generated types. That branding is now *derived from the API* rather than
 * asserted by hand in a mirror file that could drift.
 */
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"
import ts from "typescript"

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const api = path.resolve(web, "../api")
const spec = path.join(api, "openapi.json")
const out = path.join(web, "src/services/api/schema.gen.ts")
const lifecycleSpec = path.join(api, "lifecycle.json")
const lifecycleOut = path.join(web, "src/services/api/lifecycle.gen.ts")

/** OpenAPI `format` → the branded type that models it. */
const BRAND_BY_FORMAT = {
  date: "CalendarDay",
  "date-time": "Instant",
  time: "WallTime",
}

execFileSync("uv", ["run", "wild-life-openapi"], { cwd: api, stdio: "inherit" })

const ast = await openapiTS(new URL(`file://${spec}`), {
  transform(schemaObject) {
    const brand = schemaObject.type === "string" && BRAND_BY_FORMAT[schemaObject.format]
    if (!brand) return undefined
    return ts.factory.createTypeReferenceNode(brand)
  },
})

const header = `// GENERATED by \`pnpm gen:api\` from api/openapi.json — do not edit by hand.
import type { CalendarDay, Instant, WallTime } from "@/lib/date"

`

fs.writeFileSync(out, header + astToString(ast))
console.log(`wrote ${out}`)

execFileSync("uv", ["run", "wild-life-lifecycle"], { cwd: api, stdio: "inherit" })

const lifecycle = JSON.parse(fs.readFileSync(lifecycleSpec, "utf8"))
const table = Object.entries(lifecycle)
  .map(([type, statuses]) => {
    const rows = Object.entries(statuses)
      .map(([status, phase]) => `    ${JSON.stringify(status)}: ${JSON.stringify(phase)},`)
      .join("\n")
    return `  ${JSON.stringify(type)}: {\n${rows}\n  },`
  })
  .join("\n")

fs.writeFileSync(
  lifecycleOut,
  `// GENERATED by \`pnpm gen:api\` from api/lifecycle.json — do not edit by hand.
// Source of truth: api/src/wild_life/lifecycle.py

/** The shared "state of work" every entity status projects onto. */
export type LifecyclePhase = "backlog" | "active" | "blocked" | "done" | "cancelled"

/** entity type → status → phase. Total over every status \`Literal\` the API
 *  defines; \`api/tests/test_lifecycle.py\` fails if one goes unclassified. */
export const LIFECYCLE = {
${table}
} as const satisfies Record<string, Record<string, LifecyclePhase>>
`,
)
console.log(`wrote ${lifecycleOut}`)
